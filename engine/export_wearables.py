"""Read-only wardrobe metadata for fitted Ultra art and its try-on browser."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def catalog():
    from world.shop import SHOP_ITEMS, ItemCategory
    from world.habitat import Habitat
    from duck.outfits import OUTFIT_ITEMS
    from duck.seasonal_clothing import ALL_SEASONAL_ITEMS
    items = {}
    for item in SHOP_ITEMS.values():
        if item.category == ItemCategory.COSMETIC:
            items[item.id] = dict(id=item.id, name=item.name, description=item.description,
                                  slot=Habitat._get_cosmetic_slot(None, item.id),
                                  rarity=item.rarity.value, source='shop', color='')
    for item in OUTFIT_ITEMS.values():
        items.setdefault(item.id, dict(id=item.id, name=item.name, description=item.description,
                                       slot=item.slot.value, rarity=item.rarity, source='outfits', color=item.color_code))
    for item in ALL_SEASONAL_ITEMS.values():
        items.setdefault(item.item_id, dict(id=item.item_id, name=item.name, description=item.description,
                                            slot=item.slot.value, rarity=item.rarity.value, source='seasonal', color=''))
    return items


if __name__ == '__main__':
    items = catalog()
    (ROOT / 'engine/client/wearable-catalog.mjs').write_text(
        '// Generated by engine/export_wearables.py; preview metadata only.\n'
        + 'export const WEARABLE_CATALOG = ' + json.dumps(items, indent=2, ensure_ascii=False) + ';\n')
    print(f'Exported {len(items)} wearables.')
