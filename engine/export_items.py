"""Export read-only presentation metadata from every live item registry."""
import json
import sys
from pathlib import Path
from importlib import import_module

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
REGISTRIES = [('shop', 'SHOP_ITEMS'), ('items', 'ITEMS'), ('crafting', 'RECIPES'),
              ('building', 'BLUEPRINTS'), ('materials', 'MATERIALS'), ('garden', 'PLANTS'),
              ('garden', 'SEEDS'), ('collectibles', 'COLLECTIBLES'),
              ('fishing', 'FISH_DATABASE'), ('decorations', 'DECORATIONS'), ('treasure', 'TREASURES')]


def catalog():
    items = {}
    for module, registry in REGISTRIES:
        for key, value in getattr(import_module('world.' + module), registry).items():
            data = value if isinstance(value, dict) else vars(value)
            name = data.get('name', key.replace('_', ' ').title())
            category = data.get('category', data.get('item_type', module))
            rarity = data.get('rarity', 'common')
            category = getattr(category, 'value', category)
            rarity = getattr(rarity, 'value', rarity)
            if isinstance(rarity, int):
                rarity = ['common', 'uncommon', 'rare', 'epic', 'legendary'][max(0, min(4, rarity - 1))]
            entry = items.setdefault(key, {'id': key, 'name': name,
                'description': data.get('description', 'Plant these seeds in the garden.'),
                'category': category, 'rarity': rarity, 'sources': [], 'aliases': [],
                'size': data.get('size', 'small'), 'animated': data.get('animated', False)})
            entry['sources'].append(module + '.' + registry)
            if name not in entry['aliases']:
                entry['aliases'].append(name)
    return items


if __name__ == '__main__':
    items = catalog()
    target = ROOT / 'engine/client/item-catalog.mjs'
    target.write_text('// Generated by engine/export_items.py; gameplay remains in Python.\n'
                      + 'export const ITEM_CATALOG = ' + json.dumps(items, indent=2, ensure_ascii=False) + ';\n')
    print(f'Exported {len(items)} unique items from {len(REGISTRIES)} registries.')
